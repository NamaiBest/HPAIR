/**
 * One-time generator for the landing page world map.
 *
 * Samples a dot grid over land using Natural Earth data, then writes plain
 * coordinates to src/data/worldDots.ts. Run once; the app ships the output and
 * carries no geo dependency at runtime.
 *
 *   node scripts/gen-world-dots.mjs
 */
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoEquirectangular, geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/countries-110m.json");

const countries = feature(topo, topo.objects.countries);

// Natural Earth numeric ids for the five Mekong countries READY serves.
const MEKONG = new Set(["704", "418", "116", "764", "104"]); // VN, LA, KH, TH, MM
const mekong = {
  type: "FeatureCollection",
  features: countries.features.filter((f) => MEKONG.has(String(f.id))),
};

const W = 1000;
const H = 500;
const STEP = 6.2;

const projection = geoEquirectangular().fitSize([W, H], countries);

const land = [];
const region = [];

for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const inv = projection.invert([x, y]);
    if (!inv) continue;
    const [lon, lat] = inv;
    if (lat > 84 || lat < -60) continue; // trim the poles
    if (!geoContains(countries, [lon, lat])) continue;
    const pt = [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
    if (geoContains(mekong, [lon, lat])) region.push(pt);
    else land.push(pt);
  }
}

// Where the five capitals sit, for the animated markers.
const CAPITALS = {
  Hanoi: [105.83, 21.03],
  Vientiane: [102.6, 17.97],
  "Phnom Penh": [104.92, 11.56],
  Bangkok: [100.5, 13.75],
  Yangon: [96.16, 16.87],
};
const markers = Object.entries(CAPITALS).map(([name, ll]) => {
  const [x, y] = projection(ll);
  return { name, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
});

// Where the big course platforms sit, so arcs can flow from them to the region.
const SOURCES = {
  "San Francisco": [-122.4, 37.8],
  London: [-0.13, 51.5],
  Bangalore: [77.6, 12.97],
  Sydney: [151.2, -33.87],
  "São Paulo": [-46.6, -23.55],
};
const sources = Object.entries(SOURCES).map(([name, ll]) => {
  const [x, y] = projection(ll);
  return { name, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
});

const out = `// Generated by scripts/gen-world-dots.mjs. Do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};

/** Land dots outside the Mekong region. */
export const LAND_DOTS: [number, number][] = ${JSON.stringify(land)};

/** Land dots inside Vietnam, Laos, Cambodia, Thailand and Myanmar. */
export const REGION_DOTS: [number, number][] = ${JSON.stringify(region)};

/** Capitals of the five countries READY serves. */
export const MARKERS: { name: string; x: number; y: number }[] = ${JSON.stringify(markers)};

/** Cities the indexed course platforms broadcast from. */
export const SOURCES: { name: string; x: number; y: number }[] = ${JSON.stringify(sources)};
`;

fs.writeFileSync("src/data/worldDots.ts", out);
console.log(`land dots: ${land.length}, region dots: ${region.length}, markers: ${markers.length}, sources: ${sources.length}`);
